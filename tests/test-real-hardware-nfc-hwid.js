// 6. Uji Immutability Guard: Izin yang Telah Disetujui Tidak Boleh Ditimpa Scan NFC HP
test('6. Siswa yang memiliki izin resmi yang disetujui tidak ditimpa oleh tap NFC HP', () => {
  const nowMs = Date.now();
  const testNisn = '0098263610';
  const testHwid = dashboard.getOrCreateDeviceHWID();
  const randomPhoneUid = '08A1B2C3';
  const tglWib = getWibDateTime().tanggal;

  const activeSession = {
    active: true,
    status: 'waiting',
    hwid: testHwid,
    nisn: testNisn,
    nama: 'M. Ihsan Athallah',
    kelas: 'XII RPL 2',
    timestamp: nowMs,
    expiresAt: nowMs + 15000
  };

  const approvedPermitList = [
    {
      nisn: testNisn,
      status: 'disetujui',
      jenis: 'sakit',
      tanggal_mulai: tglWib,
      tanggal_selesai: tglWib
    }
  ];

  const result = processCardTap(randomPhoneUid, {
    deviceId: 'gateway-rpi-01',
    timestamp: new Date(nowMs + 1000),
    nfcSession: activeSession,
    hwidMap: {},
    permitList: approvedPermitList,
    allowTestCards: false
  });

  assert.strictEqual(result.success, true);
  assert.strictEqual(result.ignored, true, 'Tap harus diabaikan karena siswa punya izin disetujui');
  assert.strictEqual(result.reason, 'APPROVED_PERMIT_ACTIVE');
});

