// 4. Uji Pencegahan Titip Absen (Anti-Titip Absen HWID)
test('4. Perangkat yang sudah terikat untuk Siswa A TIDAK DAPAT digunakan untuk Siswa B', () => {
  const nowMs = Date.now();
  const siswaA_Nisn = '0098263610'; // M. Ihsan Athallah
  const siswaB_Nisn = '0081234567'; // Siswa Lain
  const hpIhsanHwid = 'HWID-SMKN1-IHSAN-DEVICE-01';
  const randomPhoneUid = '08D5E399';

  // HP Ihsan sudah terikat resmi di hwid_map
  const existingHwidMap = {
    [hpIhsanHwid]: {
      hwid: hpIhsanHwid,
      nisn: siswaA_Nisn,
      nama: 'M. Ihsan Athallah',
      kelas: 'XII RPL 2'
    }
  };

  // Siswa B mencoba membuka sesi menggunakan HP Ihsan
  const sessionSiswaB = {
    active: true,
    status: 'waiting',
    hwid: hpIhsanHwid,
    nisn: siswaB_Nisn,
    nama: 'Siswa Percobaan Titip',
    kelas: 'XII RPL 2',
    timestamp: nowMs,
    expiresAt: nowMs + 15000
  };

  const result = processCardTap(randomPhoneUid, {
    deviceId: 'gateway-rpi-01',
    timestamp: new Date(nowMs + 1000),
    nfcSession: sessionSiswaB,
    hwidMap: existingHwidMap,
    allowTestCards: false
  });

  assert.strictEqual(result.success, false, 'Harus ditolak karena HWID sudah terikat siswa lain');
  assert.strictEqual(result.error, 'HWID_USED_BY_OTHER');
  assert(result.message.includes('M. Ihsan Athallah'), 'Pesan harus mengidentifikasi pemilik sah');
});

