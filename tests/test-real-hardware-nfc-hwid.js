// 2. Uji Deteksi Kontak Fisik Sensor MFRC522 saat Sesi Handshake Aktif
test('2. Tap fisik NFC HP pada MFRC522 dalam window 15s berhasil dicatat (metode: nfc_hwid)', () => {
  const nowMs = Date.now();
  const testNisn = '0098263610'; // M. Ihsan Athallah
  const testHwid = dashboard.getOrCreateDeviceHWID();
  const randomPhoneUid = '083FB129'; // Random NFC UID generated by smartphone RF hardware

  const activeSession = {
    active: true,
    status: 'waiting',
    hwid: testHwid,
    nisn: testNisn,
    nama: 'M. Ihsan Athallah',
    kelas: 'XII RPL 2',
    timestamp: nowMs,
    expiresAt: nowMs + 15000 // 15 detik
  };

  const result = processCardTap(randomPhoneUid, {
    deviceId: 'gateway-rpi-01',
    timestamp: new Date(nowMs + 2000), // Ditap 2 detik setelah buka sesi
    nfcSession: activeSession,
    hwidMap: {}, // Belum terikat -> auto-bind
    allowTestCards: false
  });

  assert.strictEqual(result.success, true, 'Handshake harus berhasil');
  assert.strictEqual(result.nisn, testNisn, 'NISN harus cocok dengan sesi siswa');
  assert.strictEqual(result.nama, 'M. Ihsan Athallah');
  assert.strictEqual(result.kelas, 'XII RPL 2');

  // Periksa payload Firebase RTDB
  const tglWib = getWibDateTime(new Date(nowMs + 2000)).tanggal;
  const absensiPayload = result.firebasePaths[`absensi/${testNisn}/${tglWib}`];
  assert(absensiPayload, 'Path absensi/{nisn}/{tanggal} harus terbentuk');
  assert.strictEqual(absensiPayload.metode, 'nfc_hwid', 'Metode presensi harus nfc_hwid');
  assert.strictEqual(absensiPayload.hwid, testHwid, 'HWID harus tercatat di record');

  // Periksa penyelesaian sesi nfc_session
  const sessionUpdate = result.firebasePaths['nfc_session/gateway-rpi-01'];
  assert(sessionUpdate, 'Sesi nfc_session gateway harus di-update');
  assert.strictEqual(sessionUpdate.status, 'completed', 'Status sesi harus completed');
  assert.strictEqual(sessionUpdate.active, false, 'Sesi harus dinonaktifkan setelah tap');

  // Periksa auto-bind di hwid_map
  const hwidBinding = result.firebasePaths[`hwid_map/${testHwid}`];
  assert(hwidBinding, 'hwid_map harus mengikat perangkat ini');
  assert.strictEqual(hwidBinding.nisn, testNisn);
});

